/** Keys a setting carries with its own: compared, applied and undone together. */
export const CARRIED_WITH: Readonly<Partial<Record<SettingKey, readonly SettingKey[]>>> = {
  // a LUT is its file's name and the hash of its bytes; one without the other names another file
  gradingLutFile: ["gradingLutHash"],
};

/** A setting's label, or the key itself for one the table does not know. */
export function settingLabel(key: string): string {
  return key in SETTING_LABELS ? SETTING_LABELS[key as SettingKey] : key;
}
